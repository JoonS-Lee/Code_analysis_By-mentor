void DisplayListTitleMenu()
{
	if((ScreenIndex == SCREEN_STATE_MENU_EQUIPMENT_TOP)
			|| (ScreenIndex == SCREEN_STATE_MENU_MAINTENANCE_TOP)
			|| (ScreenIndex == SCREEN_STATE_MENU_DISPLAYSETTING_TOP))
	{
		if((OldScreenIndex != SCREEN_STATE_MENU_EQUIPMENT_TOP)
			&& (OldScreenIndex != SCREEN_STATE_MENU_MAINTENANCE_TOP)
			&& (OldScreenIndex != SCREEN_STATE_MENU_DISPLAYSETTING_TOP))
		{
			DisplayBackground();
			DisplayMenuBackgroundIcon();
			if(OldScreenIndex < SCREEN_STATE_MENU_EQUIPMENT_TOP)
				OldCurScreenIndex = 0xffff;
			CurScreenIndex = 14;
		}
	}
	else
	{
		if((OldScreenIndex & 0x0FFFFFFF) == 0)
			DisplayMenuBackgroundIcon();
		
		if((ScreenIndex & 0xF0000000) == SCREEN_STATE_MENU_EQUIPMENT_TOP)
			DisplayListTitleEquipment();
		else if((ScreenIndex & 0xF0000000) == SCREEN_STATE_MENU_MAINTENANCE_TOP)
			DisplayListTitleMaintenance();
		else if((ScreenIndex & 0xF0000000) == SCREEN_STATE_MENU_DISPLAYSETTING_TOP)
			DisplayListTitleDsiplaySetting();
		
	}		

	USHORT width = 180;
	unsigned char SetMarquee;


	if(OldCurScreenIndex != CurScreenIndex)
	{
         OldCurScreenIndex = CurScreenIndex;
         //LCD_Draw_Color(40, 6, width, FONTSIZE_1, COLOR_BLACK);
         //GUI_DisplayLeftStringAt((USHORT*)*StringSentence[CurScreenIndex], 40, 6, width, COLOR_WHITE, FONTSIZE_1);
         LCD_Draw_Color(40, 9, width, FONTSIZE_2, COLOR_BLACK);
         SetMarquee = GUI_DisplayLeftStringAt((USHORT*)*StringSentence[CurScreenIndex], 40, 9, width, COLOR_WHITE, FONTSIZE_2);
         if((((CurScreenIndex >= 75) && (CurScreenIndex <= 77)) || ((CurScreenIndex >= 91) && (CurScreenIndex <= 93))
            || (CurScreenIndex == 24)|| (CurScreenIndex == 185)||(CurScreenIndex == 190)||(CurScreenIndex == 191)||(CurScreenIndex == 192) 
			||(CurScreenIndex == 20)||((CurScreenIndex >= 33) && (CurScreenIndex <= 38))|| (CurScreenIndex == 64)|| (CurScreenIndex == 65)
			|| (CurScreenIndex == 215) || (CurScreenIndex == 216) || (CurScreenIndex == 217)
		 	|| (CurScreenIndex == 67)|| (CurScreenIndex == 68)|| (CurScreenIndex == 205)|| ((CurScreenIndex >= INDEX_STR_MANAGEMENT) && (CurScreenIndex <= INDEX_STR_MANAGEMENT+MAINTENANCE_TOTAL-1))
            || ((CurScreenIndex >= INDEX_STR_MANAGEMENT_LPG) && (CurScreenIndex <= INDEX_STR_MANAGEMENT_LPG+3))|| (CurScreenIndex == INDEX_STR_MANAGEMENT_BRAKE_COOLING_OIL_FILTER)|| (CurScreenIndex <= 1)) && SetMarquee)
            SetMarqueeTextViewTitle(CurScreenIndex);
		 else
		 {
			memset(&m_MarText[0], 0x00, 10*sizeof(MarqueeTextView));
			memset(&m_MarInfo, 0x00, sizeof(MarqueeTextInfo));	 

		 }
	}
	else if((CurScreenIndex == 190)|| (CurScreenIndex == 205)|| (CurScreenIndex == 215) || (CurScreenIndex == 216) || (CurScreenIndex == 217)) //++,--, 201019 ysm
	{
		SetMarqueeTextViewTitle(CurScreenIndex);
	}		

}	



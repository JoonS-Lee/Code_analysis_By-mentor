void DisplayMenuBackgroundIcon()
{
	unsigned int top_index = (ScreenIndex & 0x0FFFFFFF); 
	if(top_index == 0)
	{
		PCXtoBMP_16bit(6, 6, 30, 27, FL_Image.menu_icon);
	}
	else
	{
		switch(ScreenIndex & 0xF0000000)
		{
			case SCREEN_STATE_MENU_EQUIPMENT_TOP:
				PCXtoBMP_16bit(6, 6, 30, 27, FL_Image.menu_icon_setting);
				break;			
			case SCREEN_STATE_MENU_MAINTENANCE_TOP:
				PCXtoBMP_16bit(6, 6, 30, 27, FL_Image.menu_icon_maintenance);
				break;			
			case SCREEN_STATE_MENU_DISPLAYSETTING_TOP:
				PCXtoBMP_16bit(6, 6, 30, 27, FL_Image.menu_icon_display);
				break;			
		}		
	}
	
}

void DisplayListPage(UCHAR nCurPage, UCHAR nTotalPage)
{
	LCD_Draw_Color(210, 48, 6, 128, COLOR_BLACK);
	if(nTotalPage == 2)
	{
		LCD_Draw_Color(210, 48+(62*(nCurPage-1)), 6, 61,  COLOR_MENU_SCROLL);
	}
	else if(nTotalPage == 3)
	{
		LCD_Draw_Color(210, 48+(31*(nCurPage-1)), 6, 61,  COLOR_MENU_SCROLL);
	}
	else if(nTotalPage <2)
		return;
	else
	{
		UCHAR height = 128/nTotalPage;
		LCD_Draw_Color(210, 48+(height*(nCurPage-1)), 6, height,  COLOR_MENU_SCROLL);
	}
}


